void record_sx_tag_question_statistics(
    const sx_tag_question_detail::SxTagQuestionData& data,
    const std::int64_t canonical_question_count,
    const std::int64_t distinct_edges,
    GraphMetadata& metadata) {
    auto& statistics = metadata.generation_statistics;
    statistics["native_statistics_available"] = true;
    statistics["question_count"] = data.question_count;
    statistics["tag_count"] = data.tag_count;
    statistics["nontrivial_tag_count"] = data.nontrivial_tag_count;
    statistics["incidence_sum"] = data.incidence_sum;
    statistics["incidence_sum_nontrivial"] =
        data.incidence_sum_nontrivial;
    statistics["pair_occurrences"] = data.pair_occurrences;
    statistics["distinct_edges"] = distinct_edges;
    statistics["native_cover_size"] = data.incidence_sum_nontrivial;
    statistics["canonical_question_count"] = canonical_question_count;
    statistics["isolated_questions_removed"] =
        data.question_count - canonical_question_count;

    if (data.tag_count == 0) {
        statistics["min_tag_degree"] = std::monostate{};
        statistics["max_tag_degree"] = std::monostate{};
        statistics["mean_tag_degree"] = std::monostate{};
    } else {
        statistics["min_tag_degree"] = data.min_tag_degree;
        statistics["max_tag_degree"] = data.max_tag_degree;
        statistics["mean_tag_degree"] =
            sx_tag_question_detail::mean_tag_degree(data);
    }

    if (data.incidence_sum_nontrivial == 0) {
        statistics["potential_CR"] = std::monostate{};
        statistics["native_CR"] = std::monostate{};
    } else {
        statistics["potential_CR"] =
            sx_tag_question_detail::potential_cr(data);
        statistics["native_CR"] =
            2.0 * static_cast<double>(distinct_edges) /
            static_cast<double>(data.incidence_sum_nontrivial);
    }
    if (distinct_edges == 0) {
        statistics["overlap_factor"] = std::monostate{};
    } else {
        statistics["overlap_factor"] =
            static_cast<double>(data.pair_occurrences) /
            static_cast<double>(distinct_edges);
    }
}

