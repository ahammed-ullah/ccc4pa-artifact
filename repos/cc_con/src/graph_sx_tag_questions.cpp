void load_sx_tag_questions_graph(const Config& config,
                                 const std::string& configured_name,
                                 std::vector<std::vector<int>>& adj,
                                 GraphMetadata& metadata) {
    const std::filesystem::path path = config.resolve_path(
        config.require_string("graph.path"));

    metadata.name = configured_name;
    metadata.source = "file";
    metadata.type = "sx-tag-question";
    metadata.parameters["path"] = path.string();

    sx_tag_question_detail::SxTagQuestionData data =
        sx_tag_question_detail::read_sx_tag_question_file(path);

    // These values are available before the O(P) pair-generation loop. Print
    // them now so an expensive community can be stopped without waiting for a
    // construction report that is written only after graph preparation.
    sx_tag_question_detail::print_prescreen_statistics(
        configured_name, data, std::cerr);

    cornell_detail::PackedEdgeSet projected_edges;
    cornell_detail::ProjectionProgress progress(
        configured_name, "projecting tag cliques");
    std::int64_t processed_tags = 0;
    std::int64_t processed_pair_occurrences = 0;
    std::uint64_t pairs_until_progress_check = 0;

    // questions_by_tag contains sorted distinct dense IDs. A pair repeated by
    // another tag reaches the same packed key and is retained only once.
    for (std::vector<int>& questions : data.questions_by_tag) {
        cornell_detail::add_to_counter(
            processed_tags, 1, "Processed Stack Exchange tag count");
        const std::size_t degree = questions.size();
        const std::uint64_t pairs = cornell_detail::choose_two(degree);
        cornell_detail::add_to_counter(
            processed_pair_occurrences, pairs,
            "Processed Stack Exchange pair-occurrence count");

        if (projected_edges.empty() && pairs > 0) {
            // Every pair generated by the first nontrivial tag is distinct, so
            // this reservation is exact for that initial clique. Later growth
            // depends only on newly observed graph edges.
            projected_edges.reserve_for_edges(pairs);
        }

        for (std::size_t first = 0; first < degree; ++first) {
            for (std::size_t second = first + 1; second < degree; ++second) {
                projected_edges.insert(cornell_detail::edge_key(
                    questions[first], questions[second]));
                if (++pairs_until_progress_check == (UINT64_C(1) << 20)) {
                    pairs_until_progress_check = 0;
                    progress.maybe_report(
                        processed_tags,
                        processed_pair_occurrences,
                        projected_edges.size());
                }
            }
        }
        progress.maybe_report(
            processed_tags,
            processed_pair_occurrences,
            projected_edges.size());

        // The tag incidence list has no role after its clique is projected.
        // Releasing it prevents all native incidences from remaining live while
        // the global edge table approaches its peak size.
        std::vector<int>().swap(questions);
    }
    std::vector<std::vector<int>>().swap(data.questions_by_tag);

    if (projected_edges.size() > static_cast<std::size_t>(
                                     std::numeric_limits<std::int64_t>::max())) {
        throw std::runtime_error(
            "Stack Exchange projected edge count exceeds signed 64-bit range");
    }
    const std::int64_t distinct_edges =
        static_cast<std::int64_t>(projected_edges.size());

    const int maximum_question_id = data.question_count == 0
        ? -1
        : static_cast<int>(data.question_count - 1);
    cornell_detail::build_adjacency_and_release_edges(
        projected_edges, maximum_question_id, adj);

    // prepare_graph() removes these isolates immediately after this function.
    // Counting nonempty lists here records both the native question count and
    // the exact n that the canonical graph will expose to constructions.
    std::int64_t canonical_question_count = 0;
    for (const std::vector<int>& neighbors : adj) {
        if (!neighbors.empty()) {
            cornell_detail::add_to_counter(
                canonical_question_count, 1,
                "Canonical Stack Exchange question count");
        }
    }

    record_sx_tag_question_statistics(
        data, canonical_question_count, distinct_edges, metadata);
}

